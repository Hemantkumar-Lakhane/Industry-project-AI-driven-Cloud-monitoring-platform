"""
Distributed Denial of Service (DDoS) Detector (Attack Category 8)
================================================================
Identifies volumetric flooding, SYN floods, connection reset storms, and
multi-source traffic spikes overwhelming cloud workloads.

Taxonomy Index: 8
Category Slug:  ddos
Playbook ID:    PB-CS-007
"""
from typing import Dict, Any, List, Optional, Union, Set
from collections import defaultdict
from schemas.event import NormalizedEvent
from schemas.finding import SecurityFinding
from engines.base_detector import BaseDetector, detector_registry


class DDoSDetector(BaseDetector):
    """
    Evaluates volumetric and connection rate metrics for:
    1. Extreme flow connection counts (count >= 150) within sliding window.
    2. High SYN error rate (serror_rate >= 0.75) indicating SYN flood exhaustion.
    3. DDoS scenario events generated by traffic injection or Wazuh alert rules.
    """

    def __init__(self, enabled: bool = True):
        super().__init__(
            category="ddos",
            category_index=8,
            name="Distributed Denial of Service (DDoS) Detector",
            description="Identifies volumetric floods, SYN exhaustion storms, and high-rate connection abuse.",
            supported_sources=["vpc_flow", "wazuh", "cloudwatch"],
            enabled=enabled
        )

    def detect(self, events: List[Union[NormalizedEvent, Dict[str, Any]]]) -> List[SecurityFinding]:
        norm_events = self._ensure_normalized(events)
        findings: List[SecurityFinding] = []

        # Target-based grouping
        target_groups = defaultdict(list)

        for e in norm_events:
            attack_type = (e.attack_type or "").lower()
            desc = (e.description or "").lower()
            act_lower = (e.action or "").lower()
            is_ddos_explicit = "ddos" in attack_type or "denial of service" in desc or "flood" in desc or "flood" in act_lower

            # Volumetric flow indicator
            is_syn_flood = e.serror_rate >= 0.75 and e.count >= 20
            is_volume_flood = e.count >= 150

            if is_ddos_explicit or is_syn_flood or is_volume_flood:
                target = e.destination_ip or e.target_resource or "web-tier"
                target_groups[target].append(e)

        for target, flood_events in target_groups.items():
            count = len(flood_events)
            has_extreme_flow = any(e.count >= 150 or (e.serror_rate >= 0.75 and e.count >= 20) for e in flood_events)
            has_explicit_attack = any("ddos" in (e.attack_type or "").lower() for e in flood_events)
            if count < 50 and not has_extreme_flow and not has_explicit_attack:
                continue

            first_event = flood_events[0]
            triggering = flood_events[:10]

            facts = [
                f"Volumetric flood anomaly targeted resource '{target}' across {count} flow records.",
                f"High-rate connection metrics: Max connections={max(e.count for e in triggering)}, Max SYN error rate={max(e.serror_rate for e in triggering):.2f}.",
            ]
            if first_event.description:
                facts.append(f"Telemetry summary: {first_event.description}.")

            finding = self.create_finding(
                title=f"Volumetric Denial of Service (DDoS) Attack on '{target}'",
                severity="critical",
                confidence=0.96,
                detection_method="hybrid",
                triggering_events=triggering,
                observed_facts=facts,
                inferred_hypothesis=f"Coordinated traffic surge or SYN flood saturating network bandwidth and connection state tables for '{target}'.",
                affected_resource=f"endpoint:{target}",
                affected_principal="multi-source-traffic",
                telemetry_fields={"target": target, "event_volume": count},
                action_summary=f"Engage Cloudflare/AWS Shield rate limiting, activate WAF challenge mode, and drop SYN floods at edge.",
                playbook_id="PB-CS-007",
                verification_status="VERIFIED"
            )
            findings.append(finding)

        return findings


ddos_detector = DDoSDetector()
detector_registry.register(ddos_detector)
