"""
Security Finding Schema for RAM Antivirus
==========================================
Standardized, validated Pydantic schema for all findings generated by
deterministic rules, ML anomaly models, CSPM, and CIEM engines.
Strictly separates observed facts from inferred hypotheses.
"""
import uuid
from datetime import datetime, timezone
from typing import Dict, Any, Optional, List
from pydantic import BaseModel, Field, field_validator, ConfigDict


class FindingEvidence(BaseModel):
    """
    Forensic evidence backing a security finding.
    Strictly distinguishes observed, verifiable facts from inferred explanations.
    """
    model_config = ConfigDict(extra="ignore")

    triggering_event_ids: List[str] = Field(default_factory=list, description="UUIDs of telemetry events that triggered detection")
    observed_facts: List[str] = Field(default_factory=list, description="Verifiable facts directly observable in raw telemetry")
    inferred_hypothesis: Optional[str] = Field(default=None, description="Analytical interpretation or suspected adversary intent")
    missing_evidence: Optional[str] = Field(default=None, description="Critical telemetry not yet available to confirm the finding")
    telemetry_fields: Dict[str, Any] = Field(default_factory=dict, description="Key feature values observed at trigger time")


class RecommendedResponse(BaseModel):
    """
    Actionable remediation guidance, guarded with safe dry-run defaults.
    """
    model_config = ConfigDict(extra="ignore")

    playbook_id: Optional[str] = Field(default=None, description="Associated remediation playbook ID (e.g., PB-BF-001)")
    action_summary: str = Field(default="Review and investigate incident telemetry.", description="High-level analyst guidance")
    is_dry_run_supported: bool = Field(default=True, description="Whether simulation / preview mode is supported")
    requires_admin_auth: bool = Field(default=True, description="Whether execution requires elevated administrative authorization")
    estimated_duration_sec: int = Field(default=30, ge=0, description="Estimated time to execute response")


class SecurityFinding(BaseModel):
    """
    Unified security finding produced by detection engines.
    Exposed across the REST API, WebSocket streams, and UI investigation views.
    """
    model_config = ConfigDict(extra="ignore")

    finding_id: str = Field(default_factory=lambda: f"FIND-{str(uuid.uuid4())[:8].upper()}", description="Unique finding identifier")
    attack_category: str = Field(..., description="One of the 16 cloud attack categories (e.g., brute_force, iam_privilege_escalation)")
    category_index: Optional[int] = Field(default=None, ge=1, le=16, description="Index from the 16 attack taxonomy (1-16)")
    title: str = Field(..., description="Short, descriptive title of the finding")
    description: str = Field(default="", description="Detailed narrative of what was detected")

    severity: str = Field(default="medium", description="critical, high, medium, low, info")
    confidence: float = Field(default=0.8, ge=0.0, le=1.0, description="Confidence in the detection [0.0, 1.0]")
    detection_method: str = Field(default="hybrid", description="rule_based, statistical_anomaly, hybrid, posture_policy")
    status: str = Field(default="open", description="open, investigating, contained, resolved, false_positive")

    affected_resource: Optional[str] = Field(default=None, description="Cloud ARN, container ID, host, or IP address affected")
    affected_principal: Optional[str] = Field(default=None, description="Username or IAM identity involved")

    evidence: FindingEvidence = Field(default_factory=FindingEvidence)
    recommended_response: RecommendedResponse = Field(default_factory=RecommendedResponse)

    data_source: str = Field(default="SIMULATED", description="Data provenance: LIVE, SIMULATED, IMPORTED, NOT CONFIGURED")
    verification_status: str = Field(default="VERIFIED", description="Verification level: VERIFIED, SIMULATED_ONLY, NOT_CONFIGURED")

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc), description="Timestamp of finding creation in UTC")
    model_name: Optional[str] = Field(default=None, description="Specific ML model (if anomaly detection triggered finding)")
    raw_scores: Dict[str, float] = Field(default_factory=dict, description="Raw model anomaly scores or decision metrics")

    @field_validator("created_at", mode="before")
    @classmethod
    def parse_created_at(cls, v: Any) -> datetime:
        if isinstance(v, datetime):
            return v if v.tzinfo else v.replace(tzinfo=timezone.utc)
        if isinstance(v, str):
            try:
                clean_str = v.replace("Z", "+00:00")
                parsed = datetime.fromisoformat(clean_str)
                return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)
            except Exception:
                return datetime.now(timezone.utc)
        return datetime.now(timezone.utc)

    @field_validator("severity", mode="before")
    @classmethod
    def validate_severity(cls, v: Any) -> str:
        if not isinstance(v, str):
            return "medium"
        val = v.strip().lower()
        if val in ("critical", "high", "medium", "low", "info"):
            return val
        return "medium"

    @field_validator("confidence", mode="before")
    @classmethod
    def validate_confidence(cls, v: Any) -> float:
        try:
            val = float(v)
            return max(0.0, min(1.0, val))
        except (ValueError, TypeError):
            return 0.8

    @field_validator("data_source", mode="before")
    @classmethod
    def validate_data_source(cls, v: Any) -> str:
        if not isinstance(v, str):
            return "SIMULATED"
        clean = v.strip().upper()
        if clean in ("LIVE", "SIMULATED", "IMPORTED", "NOT CONFIGURED"):
            return clean
        return "SIMULATED"

    @field_validator("verification_status", mode="before")
    @classmethod
    def validate_verification_status(cls, v: Any) -> str:
        if not isinstance(v, str):
            return "VERIFIED"
        clean = v.strip().upper()
        if clean in ("VERIFIED", "SIMULATED_ONLY", "NOT_CONFIGURED"):
            return clean
        return "VERIFIED"
